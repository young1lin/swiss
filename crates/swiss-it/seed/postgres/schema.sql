-- The PostgreSQL seed, schema (SPEC §testing.it). The MySQL shapes carry over
-- (utf8 text, BIGINT past 2^53, NUMERIC precision, JSONB, microsecond timestamps,
-- composite PK with FK, PK-less duplicate rows, a 60-column wide table, 1,000 bulk
-- rows, a view) plus what only postgres has: an enum type, schemas app and audit with
-- a cross-schema foreign key, text[], uuid, and a partial index.

CREATE TYPE user_status AS ENUM ('active', 'idle', 'banned');

CREATE TABLE users (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      TEXT NOT NULL,
    email     TEXT NULL,
    status    user_status NOT NULL DEFAULT 'active',
    balance   NUMERIC(20,4) NOT NULL,
    flags     JSONB NULL,
    avatar    BYTEA NULL,
    big       BIGINT NOT NULL,
    born_at   TIMESTAMPTZ NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE orders (
    user_id BIGINT NOT NULL REFERENCES users (id),
    seq     INT NOT NULL,
    note    TEXT NULL,
    amount  NUMERIC(12,2) NOT NULL,
    placed  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, seq)
);

-- No primary key on purpose: paging must survive byte-identical duplicate rows.
CREATE TABLE events (
    at     TIMESTAMPTZ NOT NULL,
    kind   TEXT NOT NULL,
    detail JSONB NULL
);

