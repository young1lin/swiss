CREATE SCHEMA app;
CREATE SCHEMA audit;

CREATE TABLE app.documents (
    id         UUID PRIMARY KEY,
    title      TEXT NOT NULL,
    tags       TEXT[] NOT NULL DEFAULT '{}',
    created_by BIGINT NOT NULL REFERENCES public.users (id)
);

CREATE TABLE audit.log_entries (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc  UUID NOT NULL REFERENCES app.documents (id),
    at   TIMESTAMPTZ NOT NULL,
    note TEXT NULL
);

-- Partial on purpose: the browser's index list must show predicates, not pretend.
CREATE INDEX log_entries_noted_at ON audit.log_entries (at) WHERE note IS NOT NULL;

CREATE VIEW active_users AS
SELECT id, name, email, balance FROM users WHERE status = 'active';
