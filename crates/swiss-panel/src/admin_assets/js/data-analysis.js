const views = new Map              ();
let opening = 0;
const PAGE = 50;
const path = (id        )         => "/api/analysis/" + encodeURIComponent(id);
const post =    (url        , body         )                    => apiJson   (url, { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify(body) });
const current = (task              )                             => [...task.results].reverse().find(r => r.revision === task.current && !r.superseded);
function paint(v      )       { if (dbTab().kind === "sql" && (dbTab()            ).analysisId === v.task.id && dbConn().conn === v.task.conn) renderDbGrid(); }

export function dbAnalysisContext()                      {
  const t = dbTab();
  if (t.kind !== "sql" || !t.analysisId) return null;
  const v = views.get(t.analysisId);
  return v?.resultId ? { taskId: t.analysisId, resultId: v.resultId, rowIds: [...v.selected] } : null;
}

export async function dbAnalysisOpen(id        , conn = dbConn().conn)                {
  const generation = ++opening;
  const task = await apiJson              (path(id));
  if (!task || generation !== opening || dbConn().conn !== conn || task.conn !== conn) return;
  let at = dbTabs().findIndex(t => t.kind === "sql" && t.analysisId === id);
  if (at < 0) {
    const before = dbTab();
    dbOpenTabForce({ kind: "sql" });
    const made = dbTab();
    if (made.kind !== "sql" || made === before) return;
    made.analysisId = id;
    made.custom = task.title;
    at = dbTabs().indexOf(made);
  }
  const prior = views.get(id);
  const next       = { task, resultId: current(task)?.id ?? task.results.at(-1)?.id ?? null, page: null,
    selected: new Set(), busy: prior?.busy ?? false, saving: prior?.saving ?? false, pending: false, generation: (prior?.generation ?? 0) + 1, failed: false };
  // In-flight run callbacks must still update the view that reopening displays.
  views.set(id, prior ? Object.assign(prior, next) : next);
  dbActivateTab(at);
  renderDbToolbar();
  renderDbGrid();
}

async function loadPage(v      , offset        )                {
  if (!v.resultId || v.pending) return;
  const result = v.resultId, generation = ++v.generation;
  v.pending = true;
  v.failed = false;
  const page = await apiJson              (path(v.task.id) + "/results/" + encodeURIComponent(result) + "/rows?offset=" + offset + "&limit=" + PAGE);
  if (v.generation !== generation || v.resultId !== result) return;
  v.pending = false;
  if (page) v.page = page;
  else v.failed = true;
  paint(v);
}

async function refresh(v      )                {
  const task = await apiJson              (path(v.task.id));
  if (!task) return;
  v.task = task;
  paint(v);
}

async function run(v      , sql         , description         , baseRevision         )                {
  if (v.busy) return;
  v.busy = true;
  paint(v);
  try {
    if (sql != null) {
      const task = await post              (path(v.task.id) + "/revisions", { baseRevision: baseRevision ?? v.task.current, sql,
        conditions: { description: description ?? "" }, note: "" });
      if (!task) return;
      v.task = task;
    }
    // A revision is captured before waiting: a later edit cannot silently change this execution.
    const revisionId = v.task.current;
    const polling = setInterval(() => { void refresh(v); }, 1000);
    let out                                    ;
    try { out = await post(path(v.task.id) + "/execute", { revisionId }); }
    finally { clearInterval(polling); }
    if (out?.result) { v.resultId = out.result.id; v.page = null; v.selected.clear(); }
    await refresh(v);
  } finally { v.busy = false; paint(v); }
}

export function dbAnalysisButton()                    {
  const b = iconBtn("history", tr("analysis.list"), { ghost: true });
  b.onclick = ()       => { void dbAnalysisList(); };
  return b;
}

export async function dbAnalysisList()                {
  const conn = dbConn().conn;
  if (!conn) return;
  const response = await apiJson                                                               ("/api/analysis?conn=" + encodeURIComponent(conn));
  if (!response || dbConn().conn !== conn) return;
  const body = card(...response.analyses.map(t => {
    const open = btn(tr("analysis.open"));
    open.onclick = ()       => { closeSheet(); void dbAnalysisOpen(t.id, conn); };
    return row({ name: t.title, sub: t.saved ? tr("analysis.saved") : t.id, primary: open });
  }));
  if (!response.analyses.length) body.appendChild(emptyNode({ icon: "database", title: tr("analysis.empty"), hint: tr("analysis.startHint") }));
  const create = btn(tr("analysis.new"), { kind: "primary" });
  create.onclick = ()       => createSheet(conn);
  showSheet(sheet({ title: tr("analysis.list"), body: [body], foot: [create] }));
}

function createSheet(conn        )       {
  const title = h("input", { type: "text" });
  const sql = h("textarea", { rows: 6 });
  const create = btn(tr("analysis.create"), { kind: "primary" });
  create.onclick = ()       => { void (async () => {
    const task = await post              ("/api/analysis", { conn, kind: "sql", title: title.value, sql: sql.value });
    if (task) { closeSheet(); await dbAnalysisOpen(task.id, conn); }
  })(); };
  showSheet(sheet({ title: tr("analysis.new"), body: [form(field({ label: tr("analysis.title"), control: title }), field({ label: tr("analysis.sql"), control: sql }))], foot: [create] }));
}

function stateLabel(state        )         {
  const keys                         = { partial: tk("analysis.partial"), failed: tk("analysis.failed"), undetermined: tk("analysis.undetermined"), confirmed: tk("analysis.checkPassed") };
  return tr(keys[state] ?? "analysis.undetermined");
}

function button(label        , action            , disabled = false)                    {
  const b = btn(label); b.disabled = disabled; b.onclick = action; return b;
}

/** The result's whole export, paged from one frozen id; a rerun cannot change it mid-download. */
async function exportResult(v      , result                )                {
  const rows            = [];
  for (let offset = 0; ; offset += 200) {
    const page = await apiJson              (path(v.task.id) + "/results/" + result.id + "/rows?limit=200&offset=" + offset);
    if (!page) return;
    rows.push(...page.rows);
    if (!page.more) break;
  }
  const url = URL.createObjectURL(new Blob([JSON.stringify({ taskId: v.task.id, result, rows }, null, 2)], { type: "application/json" }));
  const link = h("a", { href: url, download: `analysis-${v.task.id}-${result.id}.json` });
  link.click();
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}

function resultControls(v      , result                )              {
  const column = h("select", null, (v.page?.columns ?? []).map(c => h("option", { value: c }, c)));
  const rule = h("select", null, [["unique", tk("analysis.rule.unique")], ["nonNull", tk("analysis.rule.nonNull")], ["rowCount", tk("analysis.rule.rowCount")]].map(([type, label]) => h("option", { value: type }, tr(label))));
  const expected = h("input", { type: "number", min: "0", value: String(result.rowCount) });
  const validate = button(tr("analysis.validate"), () => { void (async () => {
    const body = rule.value === "rowCount" ? { type: rule.value, expected: Number(expected.value) } : { type: rule.value, columns: [column.value] };
    if (await post(path(v.task.id) + "/results/" + result.id + "/validate", body)) await refresh(v);
  })(); });
  const other = h("select", null, v.task.results.filter(r => r.id !== result.id).map(r => h("option", { value: r.id }, r.id)));
  const comparison = h("div");
  const compare = button(tr("analysis.compare"), () => { void (async () => {
    const value = await post(path(v.task.id) + "/compare", { left: other.value, right: result.id, keys: column.value ? [column.value] : [] });
    if (value) fill(comparison, jsonCodeNode(value, true).node);
  })(); }, !other.options.length);
  const x = h("select", null, (v.page?.columns ?? []).map(c => h("option", { value: c }, c)));
  const y = h("select", null, (v.page?.columns ?? []).map(c => h("option", { value: c }, c)));
  if (y.options.length > 1) y.selectedIndex = 1;
  const kind = h("select", null, [["bar", tk("analysis.chart.bar")], ["line", tk("analysis.chart.line")], ["area", tk("analysis.chart.area")], ["scatter", tk("analysis.chart.scatter")]].map(([k, label]) => h("option", { value: k }, tr(label))));
  const chartArea = h("div");
  const draw = async ()                => {
    const chart = v.task.results.find(r => r.id === result.id)?.chart;
    if (!chart) return;
    const series = await apiJson                                                                                 (path(v.task.id) + "/results/" + result.id + "/series?x=" + encodeURIComponent(chart.x) + "&y=" + encodeURIComponent(chart.y.join(",")));
    if (!series || !chartArea.isConnected) return;
    fill(chartArea, (series.truncated || series.approximate) ? hint(tr("analysis.chartLimits")) : null,
      chart.y.map(col => resultChart({ title: chart.title || col, kind: chart.kind, points: series.points.map(p => ({ label: String(p.x), value: Number((p[col]                   ).sum) })) })));
  };
  const chart = button(tr("analysis.draw"), () => { void (async () => {
    if (!await post(path(v.task.id) + "/results/" + result.id + "/chart", { kind: kind.value, x: x.value, y: [y.value], title: "" })) return;
    await refresh(v);
  })(); });
  // The element is attached by the current paint before this microtask reads the series.
  if (result.chart) queueMicrotask(() => { void draw(); });
  return section({ cap: tr("analysis.inspect") },
    formFold({ summary: tr("analysis.validate") }, form(field({ label: tr("analysis.rule"), control: rule }), field({ label: tr("analysis.column"), control: column }), field({ label: tr("analysis.expected"), control: expected }), formActions(validate))),
    formFold({ summary: tr("analysis.compare") }, form(field({ label: tr("analysis.previousResult"), control: other }), formActions(compare), comparison)),
    formFold({ summary: tr("analysis.chart") }, form(field({ label: tr("analysis.chartType"), control: kind }), field({ label: tr("analysis.x"), control: x }), field({ label: tr("analysis.y"), control: y }), formActions(chart))), chartArea);
}

export function dbAnalysisRender(wrap             , id        )       {
  const v = views.get(id);
  if (!v) { wrap.appendChild(note(tr("analysis.loading"), { busy: true })); void dbAnalysisOpen(id); return; }
  const task = v.task;
  const result = task.results.find(r => r.id === v.resultId);
  const selected = h("select", { aria: { label: tr("analysis.version") } }, task.results.map(r => h("option", { value: r.id }, r.id)));
  selected.value = v.resultId ?? "";
  selected.onchange = ()       => { v.resultId = selected.value; v.page = null; v.selected.clear(); v.generation++; v.pending = false; paint(v); };
  const revise = actionBtn("edit", tr("analysis.edit"), { disabled: v.busy });
  revise.onclick = ()       => edit(v);
  const rerun = actionBtn("start", tr("analysis.run"), { disabled: v.busy });
  rerun.onclick = ()       => { void run(v); };
  const saveAction = task.saved ? "unbookmark" : "bookmark";
  const saveLabel = task.saved ? "analysis.unsave" : "analysis.save";
  const saved = actionBtn(saveAction, tr(v.saving ? (task.saved ? "analysis.unsaving" : "analysis.saving") : saveLabel), { disabled: v.saving });
  saved.onclick = ()       => { void (async () => {
    if (v.saving) return;
    v.saving = true; paint(v);
    try { if (await post(path(task.id) + "/save", { saved: !task.saved })) await refresh(v); }
    finally { v.saving = false; paint(v); }
  })(); };
  const lastRun = [...task.executions].reverse().find(e => e.status === "running");
  const stop = actionBtn("stop", tr("analysis.stop"), { disabled: !lastRun });
  stop.onclick = ()       => { if (lastRun) void post(path(task.id) + "/executions/" + lastRun.id + "/cancel", {}); };
  const content = wsScroll({ pad: true },
    section({ cap: task.title, tools: [rerun, saved] }, formActions(revise, selected, stop),
      hint(task.id), hint(tr("analysis.scope")), v.busy ? note(tr("analysis.running"), { busy: true }) : null,
      task.executions.at(-1)?.error ? note(task.executions.at(-1)?.error, { err: true }) : null));
  wrap.appendChild(content);
  if (!result) { content.appendChild(emptyNode({ icon: "database", title: tr("analysis.noResult"), hint: tr("analysis.startHint") })); return; }
  const exportButton = actionBtn("download", tr("analysis.export"));
  exportButton.onclick = ()       => { void exportResult(v, result); };
  content.appendChild(section({ cap: tr("analysis.result"), tools: [exportButton] },
    formActions(tag(stateLabel(result.verification)), result.truncated ? tag(tr("analysis.truncated"), { tone: "bad" }) : null,
      result.revision !== task.current ? tag(tr("analysis.historical")) : null), hint(result.id),
    hint(tr("analysis.rowCount", { n: result.rowCount })),
    ...result.checks.map(check => row({ name: check.kind, sub: stateLabel(check.state), detail: jsonCodeNode(check.measurement ?? { note: check.note, by: check.by }, true).node }))));
  if (!v.page) {
    if (v.failed) content.appendChild(button(tr("analysis.retry"), () => { void loadPage(v, 0); }));
    else { content.appendChild(note(tr("analysis.loading"), { busy: true })); if (!v.pending) void loadPage(v, 0); }
    return;
  }
  content.appendChild(resultTable({ columns: v.page.columns, rows: v.page.rows, ids: v.page.rowIds, selected: v.selected,
    label: tr("analysis.result"), selectLabel: row => tr("analysis.selectRow", { row }), onSelect: (row, on) => {
      if (on && v.selected.size >= 20) { toast(tr("analysis.selectionLimit"), true); paint(v); return; }
      if (on) v.selected.add(row); else v.selected.delete(row);
    } }));
  const page = v.page;
  content.appendChild(pager({ label: tr("analysis.pages"), prev: button(tr("analysis.prev"), () => { void loadPage(v, Math.max(0, page.offset - PAGE)); }, page.offset === 0),
    next: button(tr("analysis.next"), () => { void loadPage(v, page.offset + PAGE); }, !page.more), status: tr("analysis.range", { start: page.offset + (page.returned ? 1 : 0), end: page.offset + page.returned, total: page.total }) }));
  content.appendChild(resultControls(v, result));
}

function edit(v      )       {
  const revision = v.task.revisions.find(r => r.id === v.task.current);
  if (!revision) return;
  const sql = h("textarea", { rows: 8, value: revision.sql });
  const conditions = h("textarea", { rows: 3, value: typeof revision.conditions.description === "string" ? revision.conditions.description : JSON.stringify(revision.conditions) });
  const apply = btn(tr("analysis.runRevision"), { kind: "primary" });
  apply.onclick = ()       => { closeSheet(); void run(v, sql.value, conditions.value, revision.id); };
  showSheet(sheet({ title: tr("analysis.edit"), body: [form(field({ label: tr("analysis.conditions"), control: conditions }), field({ label: tr("analysis.sql"), control: sql }))], foot: [apply] }));
}
